#!/usr/bin/env python3
"""Bake a hand-drawn font atlas into source/font_data.h.

The port draws all of its text with a handwritten face so the HUD matches the
notebook-paper look.  Glyphs are rendered once, at 64 px, trimmed to their ink
box, and emitted as 8-bit coverage maps; the game scales them down at draw time.

    python tools/make_font.py [--font comic] [--size 64]

Only ASCII 32..126 is baked.  Glyph metrics are relative to the 64 px line so
one scale factor works for every size.
"""
import argparse
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("Pillow is required: python -m pip install pillow")

FONTS = {
    "comic": r"C:\Windows\Fonts\comicbd.ttf",
    "print": r"C:\Windows\Fonts\segoeprb.ttf",
    "print-thin": r"C:\Windows\Fonts\segoepr.ttf",
}

FIRST, LAST = 32, 126


def bake(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    line = ascent + descent
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        # Render on a generous canvas so ascenders/descenders never clip.
        pad = size
        img = Image.new("L", (size * 3, size * 3), 0)
        d = ImageDraw.Draw(img)
        d.text((pad, pad), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:
            glyphs.append((0, 0, 0, 0, int(size * 0.4), b""))
            continue
        x0, y0, x1, y1 = box
        # Offset of the ink box relative to the pen origin on the baseline.
        ox = x0 - pad
        oy = y0 - (pad + ascent)   # negative = above the baseline
        crop = img.crop(box)
        data = crop.tobytes()
        glyphs.append((x1 - x0, y1 - y0, ox, oy, int(font.getlength(ch)), data))
    return ascent, line, glyphs


def emit(path, size, ascent, line, glyphs):
    out = []
    out.append("/* Generated by tools/make_font.py - do not edit. */")
    out.append("#ifndef FONT_DATA_H")
    out.append("#define FONT_DATA_H")
    out.append("")
    out.append("#define FONT_FIRST %d" % FIRST)
    out.append("#define FONT_LAST  %d" % LAST)
    out.append("#define FONT_UNIT  %d   /* px the metrics were baked at */" % size)
    out.append("#define FONT_ASCENT %d" % ascent)
    out.append("#define FONT_LINE   %d" % line)
    out.append("")
    out.append("typedef struct {")
    out.append("    signed short w, h, ox, oy, adv;")
    out.append("    unsigned int off;")
    out.append("} FontGlyph;")
    out.append("")
    out.append("static const unsigned char font_pixels[] = {")
    blob = bytearray()
    entries = []
    for (w, h, ox, oy, adv, data) in glyphs:
        entries.append((w, h, ox, oy, adv, len(blob)))
        blob += data
    for i in range(0, len(blob), 24):
        out.append("    " + ",".join("0x%02x" % b for b in blob[i:i + 24]) + ",")
    out.append("};")
    out.append("")
    out.append("static const FontGlyph font_glyph[FONT_LAST - FONT_FIRST + 1] = {")
    for (w, h, ox, oy, adv, off) in entries:
        out.append("    { %d, %d, %d, %d, %d, %d }," % (w, h, ox, oy, adv, off))
    out.append("};")
    out.append("")
    out.append("#endif")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    total = sum(g[0] * g[1] for g in glyphs)
    print("wrote %s: %d glyphs, %d bytes of ink" % (path, len(glyphs), total))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="print", choices=sorted(FONTS))
    ap.add_argument("--size", type=int, default=64)
    ap.add_argument("-o", "--out", default=None)
    args = ap.parse_args()

    here = os.path.dirname(os.path.abspath(__file__))
    out = args.out or os.path.join(here, "..", "source", "font_data.h")
    src = FONTS[args.font]
    if not os.path.exists(src):
        sys.exit("font not found: %s" % src)
    ascent, line, glyphs = bake(src, args.size)
    emit(os.path.normpath(out), args.size, ascent, line, glyphs)


if __name__ == "__main__":
    main()
